/*
 * Le catalogue de Kaddie : l'essentiel d'une liste de courses familiale.
 * - nom : ce qui s'affiche (la marque telle qu'on l'écrit, ou le nom courant) ;
 * - alias : surnoms, abréviations, fautes courantes (« pq », « sopalin », « nutela ») ;
 * - variantes : parfums et déclinaisons reconnus, qui ne fusionnent jamais entre eux ;
 * - type : sert au rangement, n'est jamais affiché à la place du nom.
 * Il s'enrichit à la main, à partir de ce qui reste rangé en « Autre ».
 */

type Options = { type?: string; variantes?: string[] };
const p = (id: string, nom: string, rayon: AisleId, alias: string[] = [], o: Options = {}): Produit => ({ id, nom, rayon, alias, ...o });

